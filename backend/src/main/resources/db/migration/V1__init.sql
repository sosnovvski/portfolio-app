CREATE TABLE profile (
    id           integer PRIMARY KEY CONSTRAINT ck_profile_single_row CHECK (id = 1),
    version      bigint       NOT NULL DEFAULT 0,
    full_name    varchar(120) NOT NULL,
    headline_en  varchar(200) NOT NULL,
    headline_pl  varchar(200) NOT NULL,
    summary_en   text         NOT NULL,
    summary_pl   text         NOT NULL,
    location_en  varchar(120) NOT NULL,
    location_pl  varchar(120) NOT NULL,
    linkedin_url varchar(300),
    github_url   varchar(300),
    public_email varchar(254),
    created_at   timestamptz  NOT NULL DEFAULT now(),
    updated_at   timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_profile_linkedin CHECK (linkedin_url IS NULL OR linkedin_url ~ '^https://'),
    CONSTRAINT ck_profile_github CHECK (github_url IS NULL OR github_url ~ '^https://'),
    CONSTRAINT ck_profile_email CHECK (public_email IS NULL OR public_email ~ '^[^@\s]+@[^@\s]+$')
);

CREATE TABLE experience (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version     bigint       NOT NULL DEFAULT 0,
    employer    varchar(150) NOT NULL,
    client      varchar(150),
    role_en     varchar(150) NOT NULL,
    role_pl     varchar(150) NOT NULL,
    location_en varchar(120),
    location_pl varchar(120),
    start_month date         NOT NULL,
    end_month   date,
    published   boolean      NOT NULL DEFAULT false,
    created_at  timestamptz  NOT NULL DEFAULT now(),
    updated_at  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_experience_start_month CHECK (start_month = date_trunc('month', start_month)::date),
    CONSTRAINT ck_experience_end_month CHECK (end_month IS NULL OR end_month = date_trunc('month', end_month)::date),
    CONSTRAINT ck_experience_range CHECK (end_month IS NULL OR end_month >= start_month)
);

CREATE TABLE achievement (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experience_id bigint        NOT NULL REFERENCES experience (id) ON DELETE CASCADE,
    text_en       varchar(1000) NOT NULL,
    text_pl       varchar(1000) NOT NULL,
    sort_order    integer       NOT NULL CONSTRAINT ck_achievement_sort_order CHECK (sort_order >= 0)
);
CREATE INDEX ix_achievement_experience ON achievement (experience_id, sort_order);

CREATE TABLE skill_group (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version    bigint       NOT NULL DEFAULT 0,
    name_en    varchar(100) NOT NULL,
    name_pl    varchar(100) NOT NULL,
    sort_order integer      NOT NULL CONSTRAINT ck_skill_group_sort_order CHECK (sort_order >= 0),
    created_at timestamptz  NOT NULL DEFAULT now(),
    updated_at timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE skill (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id   bigint       NOT NULL REFERENCES skill_group (id) ON DELETE CASCADE,
    name       varchar(100) NOT NULL,
    sort_order integer      NOT NULL CONSTRAINT ck_skill_sort_order CHECK (sort_order >= 0)
);
CREATE INDEX ix_skill_group ON skill (group_id, sort_order);

CREATE TABLE credential (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version    bigint       NOT NULL DEFAULT 0,
    kind       varchar(20)  NOT NULL,
    title_en   varchar(200) NOT NULL,
    title_pl   varchar(200) NOT NULL,
    issuer     varchar(200) NOT NULL,
    start_year integer,
    end_year   integer,
    url        varchar(300),
    sort_order integer      NOT NULL CONSTRAINT ck_credential_sort_order CHECK (sort_order >= 0),
    created_at timestamptz  NOT NULL DEFAULT now(),
    updated_at timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_credential_kind CHECK (kind IN ('CERTIFICATION', 'EDUCATION')),
    CONSTRAINT ck_credential_years CHECK (
        (start_year IS NULL OR start_year BETWEEN 1950 AND 2100)
        AND (end_year IS NULL OR end_year BETWEEN 1950 AND 2100)
        AND (start_year IS NULL OR end_year IS NULL OR end_year >= start_year)),
    CONSTRAINT ck_credential_url CHECK (url IS NULL OR url ~ '^https://')
);

CREATE TABLE project (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version    bigint       NOT NULL DEFAULT 0,
    slug       varchar(100) NOT NULL CONSTRAINT uq_project_slug UNIQUE,
    name_en    varchar(150) NOT NULL,
    name_pl    varchar(150) NOT NULL,
    summary_en text         NOT NULL,
    summary_pl text         NOT NULL,
    status     varchar(20)  NOT NULL,
    tech       text[]       NOT NULL DEFAULT '{}',
    repo_url   varchar(300),
    live_url   varchar(300),
    sort_order integer      NOT NULL CONSTRAINT ck_project_sort_order CHECK (sort_order >= 0),
    published  boolean      NOT NULL DEFAULT false,
    created_at timestamptz  NOT NULL DEFAULT now(),
    updated_at timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_project_slug CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT ck_project_status CHECK (status IN ('PLANNED', 'IN_DEVELOPMENT', 'LIVE')),
    CONSTRAINT ck_project_repo CHECK (repo_url IS NULL OR repo_url ~ '^https://'),
    CONSTRAINT ck_project_live CHECK (live_url IS NULL OR live_url ~ '^https://')
);

CREATE TABLE contact_message (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       varchar(100)  NOT NULL CONSTRAINT ck_contact_name CHECK (btrim(name) <> ''),
    email      varchar(254)  NOT NULL CONSTRAINT ck_contact_email CHECK (email ~ '^[^@\s]+@[^@\s]+$'),
    message    varchar(5000) NOT NULL CONSTRAINT ck_contact_message CHECK (btrim(message) <> ''),
    locale     varchar(2)    NOT NULL CONSTRAINT ck_contact_locale CHECK (locale IN ('en', 'pl')),
    created_at timestamptz   NOT NULL DEFAULT now(),
    read_at    timestamptz
);
CREATE INDEX ix_contact_message_created ON contact_message (created_at DESC, id DESC);
